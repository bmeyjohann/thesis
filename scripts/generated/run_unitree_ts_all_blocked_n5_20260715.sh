#!/usr/bin/env bash
set -euo pipefail

METHOD="${1:?usage: $0 combined|combined_resume|bc_only|pref_only}"
INIT_CHECKPOINT_RESOLVED="/home/benjamin/thesis/models/unitree_mjlab_nav_thesis/unitree_goalrl_n5_r040_linear_4k_20260715/step_4000.pt"
case "$METHOD" in
  combined)
    ACTOR_BC_WEIGHT_RESOLVED=0.2
    PREF_RANK_WEIGHT_RESOLVED=1
    TOTAL_STEPS_RESOLVED=5000
    ;;
  combined_resume)
    ACTOR_BC_WEIGHT_RESOLVED=0.2
    PREF_RANK_WEIGHT_RESOLVED=1
    TOTAL_STEPS_RESOLVED=2000
    INIT_CHECKPOINT_RESOLVED="/home/benjamin/thesis/models/unitree_mjlab_nav_thesis/unitree_ts_allblocked_n1_max65_n5_combined_5000_20260715/step_1000.pt"
    ;;
  bc_only)
    ACTOR_BC_WEIGHT_RESOLVED=0.2
    PREF_RANK_WEIGHT_RESOLVED=0
    TOTAL_STEPS_RESOLVED=3000
    ;;
  pref_only)
    ACTOR_BC_WEIGHT_RESOLVED=0
    PREF_RANK_WEIGHT_RESOLVED=1
    TOTAL_STEPS_RESOLVED=3000
    ;;
  *)
    echo "unsupported method: $METHOD" >&2
    exit 2
    ;;
esac

ROOT=/home/benjamin/thesis
exec "$ROOT/scripts/run_unitree_mjlab_nav_thesis_local.sh" \
  RUN_NAME="unitree_ts_allblocked_n1_max65_n5_${METHOD}_${TOTAL_STEPS_RESOLVED}_20260715" \
