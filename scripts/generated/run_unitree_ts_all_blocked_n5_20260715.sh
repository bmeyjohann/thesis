  UPDATES_PER_STEP=4 N_STEP=5 POLICY_FREQUENCY=2 TEACHER_WARMUP_STEPS=500 \
  INTERVENTION_GATE_MODE=clearance_or_stall INTERVENTION_CLEARANCE_MODE=fixed \
  INTERVENTION_CLEARANCE_THRESHOLD=0.90 INTERVENTION_RELEASE_CLEARANCE=1.05 \
  INTERVENTION_STALL_STEPS=60 INTERVENTION_PROGRESS_EPSILON=0.04 \
  INTERVENTION_RELEASE_STEPS=4 INTERVENTION_RELEASE_PROGRESS_TOLERANCE=0.005 \
  INTERVENTION_RELEASE_ACTION_DELTA_MAX=0.80 \
