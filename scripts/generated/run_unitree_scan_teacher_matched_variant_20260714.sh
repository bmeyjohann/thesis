#!/usr/bin/env bash
set -euo pipefail

ROOT=/home/benjamin/thesis
VARIANT="${1:?usage: $0 prior|mid|relaxed}"
OUT="$ROOT/logs/unitree_mjlab/scan_teacher_matched_sweep_20260714"

case "$VARIANT" in
  prior)
    ROLLOUT_CLEARANCE=1.00
    EMERGENCY_RADIUS=0.95
    EMERGENCY_HARD_RADIUS=0.90
    CLEARANCE_WEIGHT=5.5
    ;;
  mid)
    ROLLOUT_CLEARANCE=0.82
    EMERGENCY_RADIUS=0.82
    EMERGENCY_HARD_RADIUS=0.75
    CLEARANCE_WEIGHT=5.0
    ;;
  relaxed)
    ROLLOUT_CLEARANCE=0.67
    EMERGENCY_RADIUS=0.68
    EMERGENCY_HARD_RADIUS=0.60
    CLEARANCE_WEIGHT=4.5
    ;;
  *)
    echo "unknown variant: $VARIANT" >&2
    exit 2
    ;;
esac

exec env \
  CONTROLLER=scan_teacher \
  RUN_NAME="scan_teacher_${VARIANT}_30ep" \
  OUTPUT_DIR="$OUT" \
  RECORD_VIDEO=0 \
  SEED=101 \
  NUM_ENVS=32 \
  NUM_EPISODES=30 \
  EPISODE_LENGTH_S=60 \
  GOAL_THROUGH_OBSTACLE_PROB=0.7 \
  GOAL_DISTANCE_MIN=2.8 \
  GOAL_DISTANCE_MAX=4.0 \
  MIN_GOAL_OBSTACLE_CLEARANCE=0.9 \
  DEBUG_TERRAIN_ROWS=5 \
  DEBUG_TERRAIN_COLS=10 \
  RESAMPLE_TERRAIN_TILES=1 \
  TEACHER_SCAN_BLOCK_THRESHOLD=0.12 \
  TEACHER_SCAN_BLOCK_DELTA=0.025 \
  TEACHER_SECTOR_HALF_WIDTH=0.35 \
  TEACHER_MAX_VX=0.72 \
  TEACHER_MAX_VY=0.45 \
  TEACHER_YAW_GAIN=1.2 \
  TEACHER_ALIGN_ANGLE=0.75 \
  TEACHER_MIN_FORWARD_SCALE=0.12 \
  TEACHER_BYPASS_ANGLE=1.15 \
  TEACHER_WALL_FOLLOW_STEPS=90 \
  TEACHER_WALL_FOLLOW_ANGLE=1.15 \
  TEACHER_WALL_FOLLOW_CLEAR_RISK=0.08 \
  TEACHER_CLEARANCE_WEIGHT="$CLEARANCE_WEIGHT" \
  TEACHER_ROLLOUT_HORIZON=2.4 \
  TEACHER_ROLLOUT_CLEARANCE="$ROLLOUT_CLEARANCE" \
  TEACHER_ROLLOUT_CLEARANCE_WEIGHT=24.0 \
  TEACHER_GOAL_STOP_DIST=0.40 \
  TEACHER_EMERGENCY_RADIUS="$EMERGENCY_RADIUS" \
  TEACHER_EMERGENCY_HARD_RADIUS="$EMERGENCY_HARD_RADIUS" \
  TEACHER_EMERGENCY_SPEED_SCALE=0.75 \
  TEACHER_EMERGENCY_REPULSION_WEIGHT=0.8 \
  TEACHER_EMERGENCY_TANGENT_WEIGHT=1.2 \
  TEACHER_EMERGENCY_GOAL_WEIGHT=0.4 \
  "$ROOT/scripts/run_unitree_mjlab_nav_baseline_eval_local.sh"
